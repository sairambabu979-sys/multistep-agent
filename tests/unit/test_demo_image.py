"""The demo's container image runs the tools uv.lock pins (tests/fixtures/images/demo).

The definition-of-done run gives the same verdicts in a container as on this machine only
if pytest and ruff, and what they import, are the same versions in both. The image installs
them from a requirements file generated from uv.lock, hashes and all, on a base image pinned
by digest. A lockfile bump that leaves the image behind fails here, not as a puzzling
difference in a ruff or pytest report."""

from __future__ import annotations

import re
import tomllib
from typing import Any

from packaging.markers import Marker

from tests.support.scripts import ROOT

IMAGE = ROOT / "tests/fixtures/images/demo"
DOCKERFILE = (IMAGE / "Dockerfile").read_text(encoding="utf-8")
REGENERATE = (
    "uv run python -c 'from tests.unit.test_demo_image import locked_requirements as r; "
    'print(r(), end="")\' > tests/fixtures/images/demo/requirements.txt'
)
# The image's interpreter (python:3.13-slim), for uv.lock's environment markers.
LINUX_CPYTHON_313 = {
    "extra": "",
    "implementation_name": "cpython",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "platform_python_implementation": "CPython",
    "platform_system": "Linux",
    "python_full_version": "3.13.0",
    "python_version": "3.13",
    "sys_platform": "linux",
}


def locked_requirements() -> str:
    """The image's requirements.txt: pytest and ruff, and everything they need on Linux
    CPython 3.13, each at uv.lock's version and with the hashes of uv.lock's wheels."""
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    versions: dict[str, list[dict[str, Any]]] = {}
    for package in lock["package"]:
        versions.setdefault(package["name"], []).append(package)
    wanted: dict[str, dict[str, Any]] = {}
    todo = ["pytest", "ruff"]
    while todo:
        name = todo.pop()
        if name in wanted:
            continue
        (wanted[name],) = versions[name]  # uv.lock holds one version of each
        for dependency in wanted[name].get("dependencies", []):
            marker = dependency.get("marker")
            if marker is None or Marker(marker).evaluate(LINUX_CPYTHON_313):
                todo.append(dependency["name"])
    lines = [
        "# pytest and ruff for the demo image, at uv.lock's versions and hashes. Generated by",
        f"# tests/unit/test_demo_image.py, which checks it; regenerate with: {REGENERATE}",
    ]
    for name, package in sorted(wanted.items()):
        hashes = sorted(wheel["hash"] for wheel in package["wheels"])
        lines.append(f"{name}=={package['version']} \\")
        lines += [f"    --hash={h} \\" for h in hashes[:-1]] + [f"    --hash={hashes[-1]}"]
    return "\n".join(lines) + "\n"


def test_the_image_installs_exactly_what_uv_lock_pins() -> None:
    requirements = (IMAGE / "requirements.txt").read_text(encoding="utf-8")
    assert requirements == locked_requirements(), f"regenerate it: {REGENERATE}"
    assert re.search(r"^pytest==", requirements, re.MULTILINE)
    assert re.search(r"^ruff==", requirements, re.MULTILINE)


def test_the_image_is_pinned_all_the_way_down() -> None:
    assert re.search(r"^FROM python:3\.13-slim@sha256:[0-9a-f]{64}$", DOCKERFILE, re.MULTILINE)
    assert "--require-hashes -r /tmp/requirements.txt" in DOCKERFILE


def test_ci_builds_it_for_the_demo() -> None:
    workflow = (ROOT / ".github/workflows/ci.yml").read_text(encoding="utf-8")
    assert "docker build --tag msa-demo-sandbox tests/fixtures/images/demo" in workflow
    assert 'MSA_DEMO_IMAGE: "msa-demo-sandbox"' in workflow
