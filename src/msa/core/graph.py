"""Static analysis and rendering of the transition table.

These checks look at the *declared* graph, not sampled runs, so they are proofs over the
table rather than evidence from tests:

* every phase is reachable from INTAKE;
* every live phase can reach DONE using rules alone. Global escapes (cancel, deadline,
  budget) do not count, because they reach FAILED/ABORTED trivially and would hide a phase
  that can only fail;
* terminal phases have no outgoing rules, and live phases have at least one.
"""

from __future__ import annotations

from collections import defaultdict, deque

from msa.core.table import TransitionTable
from msa.core.values import TERMINAL_PHASES, Phase

GLOBAL_ESCAPES: tuple[tuple[str, Phase, str], ...] = (
    ("CancelRequested", Phase.ABORTED, "operator cancellation"),
    ("DeadlineExceeded", Phase.FAILED, "wall-clock limit (also any event stamped after it)"),
    ("AgentFailed", Phase.FAILED, "agent invocation failed after gateway retries"),
    ("AgentRefused", Phase.FAILED, "model and every fallback declined"),
    ("(budget)", Phase.FAILED, "spend overcommits the ledger, or the next effect is unfundable"),
)


def successors(table: TransitionTable) -> dict[Phase, set[Phase]]:
    graph: dict[Phase, set[Phase]] = defaultdict(set)
    for rule in table:
        graph[rule.source] |= rule.targets
    return graph


def reachable(graph: dict[Phase, set[Phase]], origin: Phase) -> set[Phase]:
    seen, queue = {origin}, deque([origin])
    while queue:
        for nxt in graph.get(queue.popleft(), set()):
            if nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)
    return seen


def analyze(table: TransitionTable) -> list[str]:
    """Return every structural problem in ``table``; an empty list means the table is sound."""
    graph = successors(table)
    problems: list[str] = []
    from_intake = reachable(graph, Phase.INTAKE)
    for phase in Phase:
        if phase not in from_intake:
            problems.append(f"{phase.name} is unreachable from INTAKE")
        if phase in TERMINAL_PHASES:
            if graph.get(phase):
                problems.append(f"terminal {phase.name} has outgoing rules")
            continue
        if not graph.get(phase):
            problems.append(f"live {phase.name} has no outgoing rules")
        if Phase.DONE not in reachable(graph, phase):
            problems.append(f"{phase.name} cannot reach DONE through rules")
    return problems


def render_mermaid(table: TransitionTable) -> str:
    lines = ["stateDiagram-v2", f"    [*] --> {Phase.INTAKE.name}: RunStarted"]
    seen: set[tuple[Phase, str, Phase]] = set()
    for rule in table:
        for target in sorted(rule.targets, key=list(Phase).index):
            key = (rule.source, rule.event.__name__, target)
            if target is rule.source or key in seen:
                continue  # self-loops are listed in the table below the diagram
            seen.add(key)
            lines.append(f"    {rule.source.name} --> {target.name}: {rule.event.__name__}")
    lines.extend(f"    {phase.name} --> [*]" for phase in Phase if phase in TERMINAL_PHASES)
    return "\n".join(lines)


def render_markdown(table: TransitionTable) -> str:
    """The full ``docs/fsm.md`` page. CI fails if the committed file differs from this."""
    rows = [
        f"| `{rule.source.name}` | `{rule.event.__name__}` | "
        + ", ".join(f"`{t.name}`" for t in sorted(rule.targets, key=list(Phase).index))
        + " |"
        for rule in table
    ]
    escapes = [f"| `{event}` | `{target.name}` | {why} |" for event, target, why in GLOBAL_ESCAPES]
    return "\n".join(
        [
            "# Orchestrator state machine",
            "",
            "<!-- GENERATED by `msa fsm diagram --output docs/fsm.md`. Do not edit by hand. -->",
            "",
            "Generated from the transition table in `src/msa/core/transitions.py`. A contract",
            "test fails if this page and the table disagree. The design rationale is in",
            "[PLAN.md §2](PLAN.md#2-the-state-machine).",
            "",
            "```mermaid",
            render_mermaid(table),
            "```",
            "",
            "## Rules",
            "",
            "Each rule names the phases its handler may move to. The dispatcher rejects any other",
            "target at runtime.",
            "",
            "| From | Event | May move to |",
            "|---|---|---|",
            *rows,
            "",
            "## Global escapes",
            "",
            "These apply in every non-terminal phase, ahead of the rules. A terminal run cancels",
            "its pending effects and publishes its outcome.",
            "",
            "| Event | To | Why |",
            "|---|---|---|",
            *escapes,
            "",
        ]
    )
